// apps/cli/src/exportK6/emit/render.ts
// String templates of the generated export: the k6 entry script and the README.
// The engine itself (`engine.js`) is a bundle, not a template.
import type { ScenarioDefinition } from "@ocpp-cp-simulator/core/cp/application/scenario/ScenarioTypes";

// Scenario-derived text (name, id, node labels) is embedded in `//` comments
// of the generated script. A raw line terminator in any of it would close
// the comment early and splice the rest of the value in as executable code,
// so every such value is routed through this before interpolation.
export function sanitizeForComment(value: string): string {
  return value.replace(/[\r\n\u2028\u2029]/g, " ");
}

export interface ScriptOptions {
  /** The scenario, when the export has one. */
  readonly scenario?: Pick<
    ScenarioDefinition,
    "id" | "name" | "nodes" | "edges"
  >;
  /** File names under `behaviors/`, in load order. */
  readonly behaviorFiles: readonly string[];
  /** Connectors every charge point gets. */
  readonly connectors: number;
  /** Default of `CHARGERS_PER_VU`. */
  readonly chargersPerVu: number;
  readonly ocppVersion: string;
}

export function renderScript(opts: ScriptOptions): string {
  const imports = opts.behaviorFiles
    .map(
      (name, i) =>
        `import behavior${i} from ${JSON.stringify(`./behaviors/${name}`)};`,
    )
    .join("\n");
  const list = opts.behaviorFiles.map((_, i) => `behavior${i}`).join(", ");
  const scenario = opts.scenario;
  const header = scenario
    ? `// Scenario: ${sanitizeForComment(scenario.name ?? scenario.id)} (${sanitizeForComment(scenario.id)})\n//\n// Steps:\n${summarizeSteps(
        scenario,
      )
        .map((line, i) => `//   ${i + 1}. ${line}`)
        .join("\n")}\n`
    : "// Behaviors only: every charge point connects and runs the behaviors below.\n";
  return `// Generated by ocpp-cp-sim export-k6. Regenerate rather than editing; engine.js is the
// simulator's own charge point and scenario engine, bundled for k6.
${header}// OCPP version: ${opts.ocppVersion}J. Requires k6 >= v1.6.0 (stable k6/websockets). See README.md.
import exec from "k6/execution";
import { SharedArray } from "k6/data";
import { Counter, Rate, Trend } from "k6/metrics";
import { k6Options, readFleetConfig, runVu } from "./engine.js";
${imports}

const config = readFleetConfig({ CHARGERS_PER_VU: "${opts.chargersPerVu}", ...__ENV });
const scenario = ${scenario ? 'JSON.parse(open("./scenario.json"))' : "undefined"};
const behaviors = [].concat(${list});
const identities = config.idsFile
  ? new SharedArray("cp-identities", () => JSON.parse(open(config.idsFile)))
  : null;

export const options = k6Options(config, ${scenario ? "true" : "false"});

const callDuration = new Trend("ocpp_call_duration", true);
const calls = new Counter("ocpp_calls");
const errors = new Counter("ocpp_errors");
const csmsCalls = new Counter("ocpp_csms_calls");
const bootTime = new Trend("ocpp_boot_time", true);
const bootRejected = new Counter("ocpp_boot_rejected");
const cycles = new Counter("ocpp_scenario_cycles");
const cycleTime = new Trend("ocpp_scenario_duration", true);
const assertions = new Rate("ocpp_assertions");
const success = new Rate("scenario_success");

const hooks = {
  call: (action) => calls.add(1, { action }),
  result: (action, ms, error) => {
    callDuration.add(ms, { action });
    if (error) errors.add(1, { action });
  },
  csmsCall: (action) => csmsCalls.add(1, { action }),
  boot: (accepted, ms) => {
    bootTime.add(ms);
    if (!accepted) bootRejected.add(1);${scenario ? "" : "\n    success.add(accepted);"}
  },
  cycle: (ok, ms) => {
    cycles.add(1);
    cycleTime.add(ms);
    success.add(ok);
  },
  assertion: (id, ok) => assertions.add(ok, { assertion: id }),
  log: (message) => console.error(message),
};

export default async function () {
  await runVu(
    config,
    exec.vu.idInTest,
    { scenario, behaviors, identities, connectors: ${opts.connectors} },
    hooks,
  );
}
`;
}

function summarizeSteps(
  scenario: Pick<ScenarioDefinition, "nodes" | "edges">,
): string[] {
  const byId = new Map(scenario.nodes.map((n) => [n.id, n]));
  const lines: string[] = [];
  const visited = new Set<string>();
  const queue = scenario.nodes.filter((n) => n.type === "start");
  while (queue.length > 0 && lines.length < 50) {
    const node = queue.shift()!;
    if (visited.has(node.id)) continue;
    visited.add(node.id);
    if (node.type !== "start" && node.type !== "end") {
      const data = node.data as { label?: unknown };
      const label = sanitizeForComment(
        typeof data.label === "string" ? data.label : node.id,
      );
      lines.push(`${label} (${node.type})`);
    }
    for (const edge of scenario.edges) {
      const target = byId.get(edge.target);
      if (edge.source === node.id && target !== undefined) queue.push(target);
    }
  }
  return lines;
}

export function renderIdsExample(): string {
  return `${JSON.stringify(
    [
      { cpId: "CP-0001", basicPassword: "change-me" },
      { cpId: "CP-0002", basicPassword: "change-me" },
    ],
    null,
    2,
  )}\n`;
}

export function renderReadme(opts: {
  title: string;
  hasScenario: boolean;
  behaviorFiles: readonly string[];
  chargersPerVu: number;
}): string {
  const behaviors =
    opts.behaviorFiles.length > 0
      ? `\nBehaviors (built bundles, imported by \`script.js\`; every charge point loads them):\n${opts.behaviorFiles
          .map((b) => `- \`behaviors/${b}\``)
          .join("\n")}\n`
      : "";
  return `# k6 load test: ${opts.title}

Generated by \`ocpp-cp-sim export-k6\`. Requires **k6 >= v1.6.0** (stable \`k6/websockets\`).
OCPP 1.6J over \`ws://\` / \`wss://\`.

\`engine.js\` is the simulator's own charge point and scenario engine (the code the
daemon runs), bundled for k6, so every node type, wait, behavior and CSMS-initiated
call works exactly as in the simulator. \`script.js\` only wires it to k6 options and metrics.
${opts.hasScenario ? "\nThe scenario is in `scenario.json`.\n" : ""}${behaviors}
## Run

\`\`\`sh
CSMS_URL=ws://localhost:9000/ocpp CHARGERS=100 DURATION=2m k6 run script.js
CSMS_URL=wss://csms.example.com/ocpp CHARGERS=2000 CHARGERS_PER_VU=50 PROFILE=soak DURATION=8h k6 run script.js
\`\`\`

The charge point id is appended to \`CSMS_URL\` as a path segment.

## Environment variables

| Variable | Default | Meaning |
|---|---|---|
| \`CSMS_URL\` | (required) | Base OCPP WebSocket URL |
| \`CHARGERS\` | \`10\` | Charge points in the whole test |
| \`CHARGERS_PER_VU\` | \`${opts.chargersPerVu}\` | Charge points one k6 VU drives (50-100 is the sweet spot) |
| \`PROFILE\` | \`steady\` | \`steady\`: repeat the scenario until \`DURATION\`; \`once\`: run it once; \`soak\`: run it once, stay connected until \`DURATION\` |
| \`DURATION\` | \`5m\` | How long chargers keep going after the ramp |
| \`RAMP_DURATION\` | \`30s\` | Connect starts are spread evenly over this time |
| \`CP_ID_PREFIX\`, \`CP_ID_PAD\`, \`CP_ID_OFFSET\` | \`CP-\`, \`5\`, \`0\` | Ids are \`<prefix><index + 1 + offset, zero-padded>\` |
| \`CP_IDS_FILE\` | (none) | JSON array of \`{"cpId": "...", "basicPassword": "..."}\`, one per charger (see \`ids.example.json\`) |
| \`BASIC_AUTH_PASSWORD\` | (none) | Shared HTTP Basic password (security profile 1); the user name is the id |
| \`SEED\` | (random) | Seed of the simulator's random streams, per charge point |
| \`METER_VALUE_SAMPLE_INTERVAL\` | (engine default) | Seconds, configures \`MeterValueSampleInterval\` on every charge point |
| \`OCPP_VERSION\` | \`1.6\` | Only 1.6 is supported |

## Distributed runs

Charger ids derive from k6's test-wide VU id, so \`k6 run --execution-segment\` (and the
k6 operator's \`parallelism\`) split one fleet into disjoint charge points: run the same
script with the same environment on every instance. See
docs/guides/distributed-load-tests-k6-operator.md in the simulator repository.

## Sizing

Measured on k6 v2: about 2 MB of memory per running charge point, about 0.6 ms of CPU per
OCPP message, about 40 MB for the first VU and 10-20 MB per further VU. 1,000 chargers need
~2 GB and ~0.7 cores at ~1,100 messages/s. Run \`GOMAXPROCS=2\` (or the cores you can
spare) and keep \`CHARGERS_PER_VU\` at 50-100.

## Metrics

\`ocpp_call_duration\` (by \`action\`), \`ocpp_calls\`, \`ocpp_errors\` (CALLERROR, by \`action\`),
\`ocpp_csms_calls\` (CSMS-initiated CALLs, by \`action\`), \`ocpp_boot_time\`, \`ocpp_boot_rejected\`,
\`ocpp_scenario_cycles\`, \`ocpp_scenario_duration\`, \`ocpp_assertions\`, \`scenario_success\`
(threshold \`rate>0.99\` when there is a scenario).

## mTLS

k6 client certificates are configured per domain, not per charge point: add a \`tlsAuth\`
entry to \`options\` in \`script.js\`.
`;
}
