/** The entry script of a behavior export: a static import of every bundle. */
export function renderBehaviorEntry(
  bundles: readonly string[],
  opts: { ocppVersion: string; canned?: unknown },
): string {
  const imports = bundles
    .map(
      (name, i) =>
        `import behavior${i} from ${JSON.stringify(`./behaviors/${name}`)};`,
    )
    .join("\n");
  const list = bundles.map((_, i) => `behavior${i}`).join(", ");
  return `// Generated by ocpp-cp-sim export-k6 --behavior — regenerate rather than editing ocpp-runtime/.
// OCPP version: ${opts.ocppVersion} (1.6J only)
// Requires k6 >= v1.6.0 (uses the stable k6/websockets module). See README.md for env vars.
import {
  buildOptions,
  createWire,
  loadIdentities,
  requiredEnv,
  runBehaviorIteration,
  scenarioSuccess,
  type Behavior,
} from "./ocpp-runtime/index.ts";
${imports}

declare const __ENV: Record<string, string | undefined>;
declare const __VU: number;

const behaviors: Behavior[] = ([] as Behavior[]).concat(
  ...([${list}] as Array<Behavior | Behavior[]>),
);
const identities = loadIdentities(__ENV);
// The answers of ctx.accepted / ctx.rejected, written at export time from the bundled 1.6 schemas.
const canned = ${JSON.stringify(opts.canned ?? {})};

export const options = buildOptions(__ENV);

export default async function (): Promise<void> {
  const result = await runBehaviorIteration({
    behaviors,
    canned,
    env: __ENV,
    vu: __VU,
    url: requiredEnv(__ENV, "CSMS_URL"),
    wire: createWire(__ENV.OCPP_VERSION ?? ${JSON.stringify(opts.ocppVersion)}),
    identities,
  });
  if (!result.skipped) scenarioSuccess.add(result.ok);
  if (!result.ok) {
    console.error(\`behavior run failed: \${result.problems.join("; ")}\`);
  }
}
`;
}

export function renderBehaviorReadme(opts: {
  bundles: readonly string[];
  ocppVersion: string;
}): string {
  return `# k6 load test: behaviors

Generated by \`ocpp-cp-sim export-k6 --behavior\`. Requires **k6 >= v1.6.0**
(uses the stable \`k6/websockets\` module). OCPP ${opts.ocppVersion}J only.

Behaviors (built bundles, imported statically by \`behavior.k6.ts\`):
${opts.bundles.map((b) => `- \`behaviors/${b}\``).join("\n")}

## Run

\`\`\`sh
CSMS_URL=ws://localhost:9000 VUS=5 DURATION=30s RUN_FOR_MS=10000 k6 run behavior.k6.ts
CSMS_URL=... VUS=50 CHARGERS_PER_VU=20 DURATION=10m k6 run behavior.k6.ts
\`\`\`

## How an iteration runs

1. The VU connects its charge points (BootNotification each) and starts every
   behavior's \`main\` and \`onCall\` rules on each of them.
2. It stops when every \`main\` returned, or at \`RUN_FOR_MS\`, or 2 s before the
   end of a \`steady\` / \`soak\` run (\`DURATION\`), whichever is first. A behavior
   with no \`main\` and no \`RUN_FOR_MS\` serves CALLs for 60 s.
3. Stopping sets \`ctx.stopping\`, rejects every pending \`ctx.sleep\` / \`ctx.until\`
   and closes the sockets, so an iteration never waits for k6's \`gracefulStop\`.
   A \`main\` that waits on something outside the host is abandoned after 1.5 s
   and the iteration is reported failed.

Waits are timers of the host, never k6 \`sleep()\`.

## Environment variables

| Variable | Default | Meaning |
|---|---|---|
| \`CSMS_URL\` | (required) | Base OCPP WebSocket URL; the charge point id is appended as a path segment |
| \`PROFILE\`, \`VUS\`, \`DURATION\`, \`RAMP_DURATION\` | as in a scenario export | Executor shape |
| \`CHARGERS_PER_VU\` | \`1\` | Charge points one VU drives; ids get the suffix \`-1\`, \`-2\`, … |
| \`RUN_FOR_MS\` | (none) | Stop the iteration after this many ms |
| \`SEED\` | random | Seed of \`ctx.random\`; the same seed, charge point id and stream name draw the same numbers as on the simulator |
| \`CP_IDS_FILE\`, \`CP_ID_TEMPLATE\`, \`BASIC_AUTH_PASSWORD\` | as in a scenario export | Identities |

## What the k6 host does not provide

Refused at export: \`mode: "extend"\`, \`ctx.defaultBehavior\`, \`ctx.connector\`, the physical
verbs (\`plugIn\`, \`unplug\`, \`authorize\`, \`startCharging\`, \`stopCharging\`,
\`setConnectorStatus\`) and the capabilities \`physical\` and \`ocpp2.x\`.
Responses are not checked against the OCPP schema. CALLs no rule claims are
answered by the same auto-responder as in a scenario export.
`;
}
