// scripts/generate-k6-engine.ts
//
// Writes apps/cli/src/exportK6/engine.generated.ts: the k6 engine bundle
// (packages/k6-host, bundled with the real ChargePoint / ScenarioExecutor of
// packages/core), embedded as one string literal.
//
// Why: `export-k6` writes the bundle into the export directory. The published
// CLI is a single-file bundle (dist-cli/main.js) and the Tauri sidecar a
// `bun build --compile` binary, and neither ships packages/ as sources, so the
// engine is built here, before they are, and embedded (the same reason the old
// hand-written runtime was embedded).
//
// Not committed: it changes with every change to core. Run by `build:cli`,
// `build:cli:bun`, the sidecar build and CI before they bundle the CLI. Running
// the CLI from sources builds the engine on the fly instead (engineBundle.ts).
//
//   bun run gen:k6-engine
import { writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildEngine } from "../packages/k6-host/bundle/buildEngine";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outFile = join(repoRoot, "apps/cli/src/exportK6/engine.generated.ts");

const built = await buildEngine();
await writeFile(
  outFile,
  [
    "// apps/cli/src/exportK6/engine.generated.ts",
    "// GENERATED by scripts/generate-k6-engine.ts (`bun run gen:k6-engine`). Not committed.",
    "",
    `export const ENGINE_BUNDLE: string = ${JSON.stringify(built.code)};`,
    "",
  ].join("\n"),
);
console.log(
  `wrote ${outFile} (${(built.code.length / 1e6).toFixed(2)} MB; stubbed: ${built.stubbed.join(", ")})`,
);
