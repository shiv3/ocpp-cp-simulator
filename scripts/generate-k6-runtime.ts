// scripts/generate-k6-runtime.ts
//
// Writes apps/cli/src/exportK6/runtimeSources.ts: the k6 runtime files listed in
// runtimeManifest.ts, embedded as string literals.
//
// Why: `export-k6` copies the runtime into the export directory. It used to
// copy from disk, relative to `import.meta.url`, which only works when the
// CLI runs from its TypeScript sources. The published CLI is a single-file
// `bun build` bundle (dist-cli/main.js) and the Tauri sidecar is a
// `bun build --compile` binary; neither ships packages/k6-runtime/src/.
// Embedding the sources at generation time makes the subcommand independent
// of where the CLI runs from.
//
// Same arrangement as the OCPP types (`bun run gen:ocpp`): the output is
// committed, and runtimeManifest.test.ts fails when it is stale.
//
//   bun run gen:k6-runtime
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";
import { RUNTIME_FILES } from "../apps/cli/src/exportK6/runtimeManifest";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const runtimeDir = join(repoRoot, "packages/k6-runtime/src");
const outFile = join(repoRoot, "apps/cli/src/exportK6/runtimeSources.ts");

/** The module text for the given runtime file contents, before prettier. */
export function renderRuntimeSources(
  sources: ReadonlyMap<string, string>,
): string {
  const entries = [...sources]
    .map(
      ([file, text]) => `  ${JSON.stringify(file)}: ${JSON.stringify(text)},`,
    )
    .join("\n");
  return [
    "// apps/cli/src/exportK6/runtimeSources.ts",
    "// GENERATED by scripts/generate-k6-runtime.ts from packages/k6-runtime/src/.",
    "// Do not edit: run `bun run gen:k6-runtime` after changing a runtime file.",
    "// runtimeManifest.test.ts fails while this file is stale.",
    "",
    "/** The k6 runtime, keyed by its path under the export's ocpp-runtime/. */",
    "export const RUNTIME_SOURCES: Readonly<Record<string, string>> = {",
    entries,
    "};",
    "",
  ].join("\n");
}

/** Reads every manifest file; the map keeps the manifest's order. */
export async function readRuntimeSources(): Promise<Map<string, string>> {
  const sources = new Map<string, string>();
  for (const file of RUNTIME_FILES) {
    sources.set(file, await readFile(join(runtimeDir, file), "utf8"));
  }
  return sources;
}

/** The formatted module text, exactly as the generator writes it. */
export async function generateRuntimeSources(): Promise<string> {
  const code = renderRuntimeSources(await readRuntimeSources());
  return prettier.format(code, { filepath: outFile });
}

if (import.meta.main) {
  await writeFile(outFile, await generateRuntimeSources());
  console.log(`wrote ${outFile} (${RUNTIME_FILES.length} files)`);
}
