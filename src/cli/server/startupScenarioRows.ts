import type { Database } from "../../cp/domain/persistence/Database";

/**
 * `scenarios.startup_source` (schema v19, #338): which startup flag generated
 * a stored scenario row. NULL means user-authored.
 *
 * Daemon-only SQL, like `watchedScenarioFiles.ts`: the browser shares the
 * `scenarios` table's repository and has no startup flags, so it never writes
 * the column and every row it stores stays NULL.
 */

export interface StartupScenarioRow {
  readonly connector_id: number;
  readonly scenario_id: string;
  readonly startup_source: string;
}

/**
 * Record that `scenarioId` on this connector was generated by `source`.
 *
 * Runs right after `loadScenario`, whose SQLite write is synchronous, so the
 * row exists. A failed write is reported and swallowed: the scenario is
 * already loaded, and a row left unmarked reads as user-authored — the
 * direction in which the prune keeps it rather than deleting it.
 */
function markStartupScenario(
  database: Database | null | undefined,
  cpId: string,
  connectorId: number,
  scenarioId: string,
  source: string,
): void {
  try {
    database?.run(
      "UPDATE scenarios SET startup_source = ? " +
        "WHERE cp_id = ? AND connector_id = ? AND scenario_id = ?",
      [source, cpId, connectorId, scenarioId],
    );
  } catch (err) {
    process.stderr.write(
      `[server] could not record startup provenance for ${cpId}/${connectorId}/${scenarioId}: ` +
        `${err instanceof Error ? err.message : String(err)}\n`,
    );
  }
}

/**
 * Run a startup load and record `source` on the row it installs — unless that
 * row already existed as a user-authored one (#338).
 *
 * A flag that loads over an existing NULL row (a charge point's seeded
 * default, a scenario an operator loaded under the same id, a row written
 * before schema v19) leaves it user-authored: marking it would hand it to the
 * prune, and a later boot without the flag would delete a scenario the flag
 * never created. A row the flag creates, or one it marked before, carries the
 * flag. Returns the load's scenario id.
 */
export function loadWithStartupProvenance(
  database: Database | null | undefined,
  cpId: string,
  connectorId: number,
  source: string,
  load: () => string,
): string {
  const userAuthored = userAuthoredScenarioIds(database, cpId, connectorId);
  const scenarioId = load();
  if (userAuthored !== null && !userAuthored.has(scenarioId)) {
    markStartupScenario(database, cpId, connectorId, scenarioId, source);
  }
  return scenarioId;
}

/**
 * Hand rows back to the user: a scenario saved or loaded through the control
 * plane or the web console is what the operator wants kept, even when a
 * startup flag first generated it, so it loses its provenance and the prune
 * leaves it alone. A failed write is reported and swallowed, like a failed
 * mark: the row then stays the flag's, as before the save.
 */
export function clearStartupProvenance(
  database: Database | null | undefined,
  cpId: string,
  connectorId: number | null,
  scenarioIds: readonly string[],
): void {
  if (!database || scenarioIds.length === 0) return;
  try {
    database.run(
      "UPDATE scenarios SET startup_source = NULL " +
        `WHERE cp_id = ? AND connector_id = ? AND scenario_id IN (${scenarioIds
          .map(() => "?")
          .join(", ")}) AND startup_source IS NOT NULL`,
      [cpId, connectorId ?? 0, ...scenarioIds],
    );
  } catch (err) {
    process.stderr.write(
      `[server] could not clear startup provenance for ${cpId}/${connectorId ?? 0}: ` +
        `${err instanceof Error ? err.message : String(err)}\n`,
    );
  }
}

/** Ids of the rows on this connector that carry no provenance, or `null` when
 *  they cannot be read — the load then marks nothing, the direction in which
 *  no row is ever handed to the prune by mistake. */
function userAuthoredScenarioIds(
  database: Database | null | undefined,
  cpId: string,
  connectorId: number,
): Set<string> | null {
  try {
    return new Set(
      (
        database?.all<{ scenario_id: string }>(
          "SELECT scenario_id FROM scenarios " +
            "WHERE cp_id = ? AND connector_id = ? AND startup_source IS NULL",
          [cpId, connectorId],
        ) ?? []
      ).map((row) => row.scenario_id),
    );
  } catch (err) {
    process.stderr.write(
      `[server] could not read scenario provenance for ${cpId}/${connectorId}: ` +
        `${err instanceof Error ? err.message : String(err)}\n`,
    );
    return null;
  }
}

/**
 * Every startup-generated row stored for a charge point. A read that fails
 * returns nothing — the prune then removes nothing, said out loud.
 */
export function listStartupScenarioRows(
  database: Database | null | undefined,
  cpId: string,
): StartupScenarioRow[] {
  try {
    return (
      database?.all<StartupScenarioRow>(
        "SELECT connector_id, scenario_id, startup_source FROM scenarios " +
          "WHERE cp_id = ? AND startup_source IS NOT NULL " +
          "ORDER BY connector_id, scenario_id",
        [cpId],
      ) ?? []
    );
  } catch (err) {
    process.stderr.write(
      `[server] could not read startup scenario rows for ${cpId}: ` +
        `${err instanceof Error ? err.message : String(err)}\n`,
    );
    return [];
  }
}

/**
 * Delete one stored scenario row. For the prune's leftover case only: a row
 * whose id the in-memory map holds on another connector, which
 * `removeScenario` therefore declines to touch.
 */
export function deleteScenarioRow(
  database: Database | null | undefined,
  cpId: string,
  connectorId: number,
  scenarioId: string,
): void {
  database?.run(
    "DELETE FROM scenarios WHERE cp_id = ? AND connector_id = ? AND scenario_id = ?",
    [cpId, connectorId, scenarioId],
  );
}
